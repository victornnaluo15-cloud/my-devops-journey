#Python list
fruits = ["apple", "banana", "orange", "mango"]

print(fruits)

#Accessing an item
print(fruits[0])

# Adding an item
fruits.append("grape")
print(fruits)

# Removing an item
fruits.remove("banana")
print(fruits)

# Changing an item
fruits[0] = "watermelon"
print(fruits)

# Finding the number of items
print(len(fruits))